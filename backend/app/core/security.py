"""Authentication: verify tokens the identity provider signed. Nothing else.

**Neon Managed Better Auth is MaliHub's identity provider.** This module
contains no password handling, no user table, no signup, no login, no session
store, and no way to mint a token. It takes a JWT the auth service already
signed and answers one question: *is this a valid, unexpired token for a real
user?*

That boundary is the reason the backend can exist without becoming a second
authentication system — the failure mode where two services each own half of
"who is this user" and drift apart. Login/signup stay in the Next.js app
(`src/lib/auth/*`, `src/app/(auth)/*`); the frontend forwards the access token
it already holds as `Authorization: Bearer <token>`.

**A valid token is authentication, not authorization.** Three properties of
Neon Auth's JWTs make that distinction load-bearing rather than philosophical:

* `sub` is the **provider's** user id (`neon_auth.user.id`), *not*
  `public.users.id`. MaliHub's own id is generated by the application and is
  what every foreign key in the schema targets, so it deliberately does not
  change when the identity provider does. The bridge is `users.auth_user_id`,
  and crossing it is a database read — see `core/identity.py`. A backend that
  used `sub` as `users.id` would not fail loudly: it would verify tokens
  successfully and then find nothing, or find someone else's rows.
* There is **no `app_metadata`** claim. The retired implementation mirrored
  MaliHub's authoritative state into that claim so middleware could read role
  and onboarding without a query. The cache could lag the database, and a
  stale `onboarded` is what produced the /dashboard ↔ /complete-profile
  redirect loop this repository fixed twice. Neon Auth accepts no custom
  claims, so the cache is gone rather than reimplemented — `role`,
  `is_onboarded` and `has_seller_profile` are read from Postgres.
* The `role` claim a Neon Auth JWT *does* carry is the string `"authenticated"`
  — a Postgres/RLS role, not MaliHub's application role. Reading it as an app
  role makes every logged-in user identical. It is ignored here, deliberately
  and with a test asserting that a token claiming `"role": "SUPER_ADMIN"` does
  not produce a staff context.

Because resolution is a database read, this backend can do what the stateless
Supabase-era verifier could not: **enforce bans and deactivations immediately**
rather than at token expiry. The cost is one indexed lookup per authenticated
request, which is the price of an answer that cannot go stale.

What is *not* implemented here, deliberately:

* **Token revocation beyond expiry.** A stolen token stays cryptographically
  valid until `exp`. Ban enforcement above covers the account-level case;
  per-token revocation needs a denylist in Redis and is a later phase.
* **Refresh.** Refresh tokens are for the frontend's auth client, never for
  this API. A 401 here means "get a fresh token and retry".

Rollback: `SupabaseJwtVerifier` and the `SUPABASE_*` settings are retained
unmodified and are selected only by `AUTH_PROVIDER=supabase-legacy`, so
reverting is a configuration change rather than a revert of this service
(`docs/auth/MIGRATION.md` §9). Exactly one provider is ever active — a backend
that verified both would honour a stale Supabase token for as long as it
remained unexpired after the cutover.
"""

